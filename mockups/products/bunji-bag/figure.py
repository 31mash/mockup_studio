def figure(x: float, y: float, height: float, uid: str = 'fig') -> str:
    """The figure as an SVG group: (x, y) is the top-left of the 660 x 1260
    drawing space in artwork units; `height` is the drawing space's height."""
    s = height / 1260.0
    defs = []
    pats = {}

    def pattern(spec):
        if spec not in pats:
            sp, lw, ang = spec
            pid = f'{uid}-h{len(pats)}'
            pats[spec] = pid
            defs.append(
                f'<pattern id="{pid}" patternUnits="userSpaceOnUse" width="{sp}" height="{sp}" '
                f'patternTransform="rotate({ang})"><rect x="0" y="0" width="{sp}" height="{lw}" fill="{INK}"/></pattern>'
            )
        return pats[spec]

    body = []
    for i, (name, d) in enumerate(PARTS):
        if name.endswith('shoe'):
            body.append(f'<path d="{d}" fill="{INK}" stroke="{INK}" stroke-width="3.5" stroke-linejoin="round"/>')
            continue
        cid = f'{uid}-clip-{i}'
        defs.append(f'<clipPath id="{cid}"><path d="{d}"/></clipPath>')
        body.append(f'<path d="{d}" fill="#ffffff"/>')
        for part, spec, sd in SHADE:
            if part == name:
                body.append(f'<path d="{sd}" fill="url(#{pattern(spec)})" clip-path="url(#{cid})"/>')
        body.append(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="4" stroke-linejoin="round"/>')
        if name == 'head':
            body.append(f'<path d="{HAIR}" fill="{INK}"/>')
            for sd in HAIR_STRANDS:
                body.append(f'<path d="{sd}" fill="none" stroke="#ffffff" stroke-width="2.2" stroke-linecap="round"/>')
            body.append(f'<path d="{EAR}" fill="#ffffff" stroke="{INK}" stroke-width="3"/>')
            body.append(f'<path d="{MOUSTACHE}" fill="{INK}"/>')
    for d, w in HIGHLIGHTS:
        body.append(f'<path d="{d}" fill="none" stroke="#ffffff" stroke-width="{w}" stroke-linecap="round"/>')
    for d, w in LINES + GROUND:
        body.append(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{w}" stroke-linecap="round"/>')
    return f'<defs>{"".join(defs)}</defs><g transform="translate({x:.2f},{y:.2f}) scale({s:.5f})">{"".join(body)}</g>'
